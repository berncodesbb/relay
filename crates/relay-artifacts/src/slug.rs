/// Look up the NFKD/mark-stripped/lowercased contribution of one code point.
fn decompose(code_point: u32) -> Option<&'static str> {
    SLUG_DECOMPOSITIONS
        .binary_search_by(|(entry, _)| entry.cmp(&code_point))
        .ok()
        .map(|index| SLUG_DECOMPOSITIONS[index].1)
}

/// The slug for an artifact title: lowercase, dashed, no leading or trailing
/// dashes, at most 60 UTF-16 units long, and `untitled` when nothing remains.
pub fn slugify(title: &str) -> String {
    // Decompose, strip marks, lowercase (the table contribution already is).
    let mut lowered = String::with_capacity(title.len());
    for ch in title.chars() {
        match ch {
            'A'..='Z' => lowered.push(ch.to_ascii_lowercase()),
            _ if (ch as u32) < 0x80 => lowered.push(ch),
            _ => match decompose(ch as u32) {
                Some(contribution) => lowered.push_str(contribution),
                None => lowered.push(ch),
            },
        }
    }
    // Collapse every run of non-[a-z0-9] into a single dash.
    let mut dashed = String::with_capacity(lowered.len());
    let mut pending_dash = false;
    for ch in lowered.chars() {
        if ch.is_ascii_lowercase() || ch.is_ascii_digit() {
            if pending_dash {
                dashed.push('-');
                pending_dash = false;
            }
            dashed.push(ch);
        } else {
            pending_dash = true;
        }
    }
    if pending_dash {
        dashed.push('-');
    }
    // Trim leading/trailing dashes. A leading dash means the first run was
    // non-alphanumeric; `pending_dash` above already emitted exactly one.
    let trimmed = dashed.trim_matches('-');
    // Truncate to 60 UTF-16 code units.
    let mut units: Vec<u16> = trimmed.encode_utf16().collect();
    units.truncate(60);
    let mut truncated = String::from_utf16_lossy(&units);
    // Strip any trailing dashes introduced by the truncation.
    while truncated.ends_with('-') {
        truncated.pop();
    }
    if truncated.is_empty() {
        "untitled".to_string()
    } else {
        truncated
    }
}
